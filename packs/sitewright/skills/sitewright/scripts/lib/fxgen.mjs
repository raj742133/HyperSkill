// Writes the effects layer of a generated project: the chosen component files, one fx.css, the slot file the pages import
// (index.tsx) and the micro-interaction attacher (micro.tsx). Called by scaffold.mjs when the 'fx' flag is set.

import fs from 'node:fs';
import path from 'node:path';
import { effectPlan, BACKGROUNDS, HEADLINES, BUTTONS, CARDS, REVEALS, EXTRAS, PRESETS, PLACES, FIGURES } from '../effects.mjs';
import { UI } from '../ui.mjs';
import { slotsSource } from './figures-slots.mjs';

const HEADLINE_FILES = {
  'split-chars': 'SplitChars', 'split-words': 'SplitWords', 'blur-in': 'BlurIn', typewriter: 'Typewriter',
  gradient: 'Gradient', shimmer: 'Shimmer', scramble: 'Scramble', rotate: 'Rotate',
};
const BACKGROUND_FILES = {
  aurora: 'Aurora', mesh: 'Mesh', dots: 'Dots', particles: 'Particles', stars: 'Stars',
  beams: 'Beams', waves: 'Waves', grid: 'Grid', grain: 'Grain', spotlight: 'Spotlight',
};
/** The attributes on <html> that switch the button, card and reveal effects on (they are matched by the generated css). */
export function fxHtmlAttrs(fx) {
  return [['buttons', fx.buttons, 'none'], ['cards', fx.cards, 'none'], ['reveal', fx.reveal, 'rise']].filter(([, v, d]) => v !== d).map(([k, v]) => ` data-fx-${k}="${v}"`).join('');
}

/** Every file and folder under src/components/fx/ that generateFx writes (the gallery's Playground.tsx is not one of them). */
export const FX_GENERATED = ['bg', 'text', 'micro', 'figures', 'ui', 'useCanvasLoop.ts', 'CountUp.tsx', 'fx.css', 'index.tsx', 'micro.tsx', 'catalog.tsx'];

const CANVAS = new Set(['dots', 'particles', 'stars']);

/**
 * @param {object} o
 * @param {object} o.fx        resolved effects (resolveEffects)
 * @param {boolean} o.landing  true when the landing module is present (it owns the hero the HeroBackground slot sits in)
 * @param {boolean} o.all      true for the gallery module: every effect is copied so the page can preview all of them
 * @param {string} o.templates path to the templates folder
 * @param {object} o.tokens    __TOKEN__ values
 * @param {(rel: string, content: string) => void} o.put
 * @param {(text: string, tokens: object, file: string) => string} o.fill
 */
export function generateFx({ fx, landing, all, templates, tokens, put, fill }) {
  const dir = path.join(templates, 'fx');
  const read = (rel) => fs.readFileSync(path.join(dir, rel), 'utf8').replace(/\r\n/g, '\n');
  const plan = effectPlan(fx, { all });

  // The shared canvas hook is only worth shipping when a canvas background is actually in use.
  const usesCanvas = all || CANVAS.has(fx.heroBackground) || CANVAS.has(fx.loginBackground);
  const files = plan.files.filter((f) => usesCanvas || f !== 'useCanvasLoop.ts');
  for (const rel of files) put(`src/components/fx/${rel}`, fill(read(rel), tokens, `fx/${rel}`));

  const css = plan.css.map((c) => `/* ${c} */\n${fill(read(`css/${c}.css`), tokens, `fx/css/${c}.css`)}`).join('\n');
  put('src/components/fx/fx.css',
    '/* Generated by Sitewright from the effects chosen in site.json. Every rule is scoped by a data-fx-* attribute or a class, so unused rules are inert. */\n' + css);

  // The slots the pages import. Every site has all of them (a "none" choice renders nothing), so switching an effect later only
  // rewrites this folder - the pages never change. Swap a file name here to change an effect by hand.
  const lines = [
    '// Generated by Sitewright. The slots the pages use: change which file a slot points at to change the effect.',
    "import type { Parts } from './text/split';",
    `import Chosen from './text/${HEADLINE_FILES[fx.headline] ?? 'Plain'}';`,
    fx.headline === 'rotate'
      ? `export function Headline(p: Parts) {\n  return <Chosen {...p} words={${JSON.stringify(fx.rotateWords)}} />;\n}`
      : 'export function Headline(p: Parts) {\n  return <Chosen {...p} />;\n}',
  ];
  if (landing) {
    if (fx.heroBackground === 'territory') lines.push("export { Territory as HeroBackground } from '@/components/landing/Territory';");
    else if (fx.heroBackground === 'none') lines.push('export function HeroBackground() {\n  return null;\n}');
    else lines.push(`export { default as HeroBackground } from './bg/${BACKGROUND_FILES[fx.heroBackground]}';`);
  }
  if (fx.loginBackground === 'none') lines.push('export function LoginBackground() {\n  return null;\n}');
  else lines.push(`export { default as LoginBackground } from './bg/${BACKGROUND_FILES[fx.loginBackground]}';`);
  if (fx.extras.includes('count-up')) lines.push("export { default as CountUp } from './CountUp';");
  else lines.push("export function CountUp({ value }: { value: number }) {\n  return <>{value.toLocaleString('en-GB')}</>;\n}");
  lines.push("export { Figure } from './figures/Slots';");
  put('src/components/fx/index.tsx', lines.join('\n') + '\n');
  // <Figure place=... /> and <Figure name=... />: the component, and the settings the project's own figure sync reads to keep it in line with the code
  const places = Object.keys(PLACES);
  put('src/components/fx/figures/Slots.tsx', slotsSource({ places, chosen: fx.figures, named: [], intensity: fx.figureIntensity }));
  put('src/components/fx/figures/config.json', JSON.stringify({ places, chosen: fx.figures, intensity: fx.figureIntensity, named: [] }, null, 2) + '\n');

  // The components a page can import: `import { HoldToConfirm } from '@/components/fx/ui'`. The gallery gets all of them, with their demos.
  const uiIds = all ? Object.keys(UI) : (fx.components ?? []);
  if (uiIds.length || all) {
    put('src/components/fx/ui/index.ts', ['// Generated by Sitewright. The components chosen in site.json (effects.components); add one by name there, or run scaffold --apply-effects.', ...uiIds.map((id) => `export { default as ${UI[id].component} } from './${UI[id].component}';`), ...(uiIds.length ? [] : ['export {};']), ''].join('\n'));
    if (all) put('src/components/fx/ui/demos.tsx', ["// Generated by Sitewright: every component's demo, for the /effects gallery.", "import type { ComponentType } from 'react';", ...uiIds.map((id) => `import { Demo as ${UI[id].component}Demo } from './${UI[id].component}';`), '', `export const UI_DEMOS: { id: string; label: string; desc: string; source: string; group: string; use: string; Demo: ComponentType }[] = [`, ...uiIds.map((id) => `  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(UI[id].label)}, desc: ${JSON.stringify(UI[id].desc)}, source: ${JSON.stringify(UI[id].source)}, group: ${JSON.stringify(UI[id].group)}, use: ${JSON.stringify(UI[id].use)}, Demo: ${UI[id].component}Demo },`), '];', ''].join('\n'));
  }

  // In the gallery the page-level extras are switched on and off by the playground itself, so only the button/card ones are global.
  const mods = all ? plan.micro.filter((m) => ['magnetic', 'ripple', 'tilt', 'spotlight'].includes(m)) : plan.micro;
  put('src/components/fx/micro.tsx', mods.length
    ? [
      "'use client';",
      '',
      "import { useEffect } from 'react';",
      ...mods.map((m) => `import { attach as ${m} } from './micro/${m}';`),
      '',
      '/** Attaches the chosen button, card and page-level micro-interactions once, and removes them on unmount. */',
      'export function FxMicro() {',
      '  useEffect(() => {',
      `    const offs = [${mods.map((m) => `${m}()`).join(', ')}];`,
      '    return () => offs.forEach((off) => off());',
      '  }, []);',
      '  return null;',
      '}',
      '',
    ].join('\n')
    : "'use client';\n\nexport function FxMicro() {\n  return null;\n}\n");

  if (all) put('src/components/fx/catalog.tsx', catalog());
}

const info = (table) => Object.entries(table).map(([id, e]) => ({ id, label: e.label, desc: e.desc }));
const ident = (id) => id.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));

/** Everything the /effects playground needs: every component by id, plus the labels and presets from the registry. */
function catalog() {
  const bg = Object.keys(BACKGROUNDS);
  const hl = Object.keys(HEADLINES);
  const extraMicro = { 'cursor-glow': 'cursorGlow', 'scroll-progress': 'scrollProgress', 'click-spark': 'clickSpark' };
  const out = [
    '// Generated by Sitewright: every effect, by id, for the /effects playground.',
    "import type { ComponentType } from 'react';",
    "import type { Parts } from './text/split';",
    "import Plain from './text/Plain';",
    "import type { Figure as MountedFigure, HairlineOptions } from './figures/mount';",
    ...Object.keys(FIGURES).map((id) => `import { ${id} as ${ident(id)}Fig } from './figures/factories/${id}';`),
    ...bg.map((id) => `import ${ident(id)}Bg from './bg/${BACKGROUND_FILES[id]}';`),
    ...hl.map((id) => `import ${ident(id)}Text from './text/${HEADLINE_FILES[id]}';`),
    ...Object.entries(extraMicro).map(([, m]) => `import { attach as ${m} } from './micro/${m}';`),
    "export { default as CountUp } from './CountUp';",
    '',
    `export const BACKGROUND_COMPONENTS: Record<string, ComponentType> = { ${bg.map((id) => `'${id}': ${ident(id)}Bg`).join(', ')} };`,
    `export const HEADLINE_COMPONENTS: Record<string, ComponentType<Parts & { words?: string[] }>> = { none: Plain, ${hl.map((id) => `'${id}': ${ident(id)}Text`).join(', ')} };`,
    `export const FIGURE_FACTORIES: Record<string, (el: HTMLElement, options?: HairlineOptions) => MountedFigure> = { ${Object.keys(FIGURES).map((id) => `'${id}': ${ident(id)}Fig`).join(', ')} };`,
    `export const EXTRA_ATTACH: Record<string, () => () => void> = { ${Object.entries(extraMicro).map(([id, m]) => `'${id}': ${m}`).join(', ')} };`,
    `export const INFO = ${JSON.stringify({
      background: info(BACKGROUNDS), headline: info(HEADLINES), buttons: info(BUTTONS), cards: info(CARDS), reveal: info(REVEALS), extras: info(EXTRAS), presets: PRESETS,
      figures: info(FIGURES), places: Object.entries(PLACES).map(([id, p]) => ({ id, label: p.label, desc: p.desc, suggest: p.suggest, needs: p.needs })),
    }, null, 2)} as const;`,
    '',
  ];
  return out.join('\n');
}
