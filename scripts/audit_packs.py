#!/usr/bin/env python3
"""A pattern scan of every bundled third-party pack (and the skills written here), written to docs/pack-audit.md.

    python3 scripts/audit_packs.py            write docs/pack-audit.md and docs/pack-audit.json
    python3 scripts/audit_packs.py --check    exit 1 if they are out of date
    python3 scripts/audit_packs.py DIR ...    scan other folders and print the result (nothing is written)

This is NOT a security review. It looks for text that deserves a human's attention before a skill is enabled: network calls, running other
programs, downloading and running code, reading credentials or the home folder, and obfuscated blobs. A hit is a place to look, not a finding;
no hits does not mean safe. Standard library only; nothing is executed.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT_EXT = {".py", ".js", ".mjs", ".cjs", ".ts", ".tsx", ".sh", ".bash", ".zsh", ".ps1", ".rb", ".go", ".md", ".json", ".yml", ".yaml", ".toml", ".html", ".css"}
MAX = 1024 * 1024
CATEGORIES = {
    "network": ("Makes network requests", re.compile(r"\b(requests\.(get|post|put|delete|request)|urllib\.request|http\.client|httpx\.|aiohttp|fetch\(|axios|XMLHttpRequest|WebSocket\(|new Request\(|curl\s+-|wget\s)")),
    "run-programs": ("Runs other programs", re.compile(r"(subprocess\.|os\.system\(|os\.popen\(|child_process|execSync|spawnSync|\bspawn\(|\bexecFile\(|Popen\()")),
    "dynamic-code": ("Builds and runs code from text", re.compile(r"((?<![\w.])eval\(|(?<![\w.])exec\(\s*[^)]|new Function\(|compile\([^)]*['\"]exec['\"])")),
    "download-and-run": ("Downloads or installs software", re.compile(r"(curl[^|\n]*\|\s*(ba)?sh|npx\s+-y|npm\s+(i|install)\b|pip3?\s+install|brew\s+install|apt(-get)?\s+install|go\s+install|cargo\s+install)")),
    "credentials": ("Reads credentials, tokens or the home folder", re.compile(r"(~/\.ssh|\.aws/credentials|\.netrc|\.npmrc|id_rsa|os\.environ\[?['\"][A-Z_]*(KEY|TOKEN|SECRET|PASSWORD)|process\.env\.[A-Z_]*(KEY|TOKEN|SECRET|PASSWORD)|keychain|Login Data|Cookies\b|expanduser\(['\"]~|Path\.home\(\)|os\.homedir\(\)|\$HOME)")),
    "writes-outside": ("Writes outside the project", re.compile(r"(~/\.claude|\.claude/(skills|settings)|/etc/|/usr/local/|crontab|launchctl|systemctl|\bchmod\s+\+x\s+/)")),
    "obfuscation": ("Decodes hidden text", re.compile(r"(b64decode\(|atob\(|fromCharCode\(|\\x[0-9a-f]{2}\\x[0-9a-f]{2}\\x[0-9a-f]{2}|[A-Za-z0-9+/]{300,}={0,2})")),
}
SHOW = 4  # hits listed per category per folder


def scan_dir(path):
    hits = {k: [] for k in CATEGORIES}
    counts = {k: 0 for k in CATEGORIES}
    files = 0
    hosts = set()
    for dirpath, dirnames, filenames in os.walk(path, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if d not in (".git", "node_modules", "__pycache__"))
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            if os.path.islink(full) or os.path.splitext(fn)[1].lower() not in TEXT_EXT:
                continue
            try:
                if os.path.getsize(full) > MAX:
                    continue
                with open(full, encoding="utf-8", errors="replace") as f:
                    lines = f.read().split("\n")
            except OSError:
                continue
            files += 1
            rel = os.path.relpath(full, path).replace(os.sep, "/")
            doc = fn.lower().endswith((".md", ".json", ".css", ".html"))     # prose and data: URLs and install commands there are documentation
            for n, line in enumerate(lines, 1):
                for m in re.finditer(r"https?://([A-Za-z0-9.-]+)", line):
                    if not doc:
                        hosts.add(m.group(1).lower())
                if len(line) > 4000:
                    continue
                for k, (_, rx) in CATEGORIES.items():
                    if doc and k not in ("download-and-run", "credentials"):
                        continue
                    if doc and fn.lower().endswith((".json", ".css", ".html")):
                        continue
                    if rx.search(line):
                        counts[k] += 1
                        if len(hits[k]) < SHOW:
                            hits[k].append({"file": rel, "line": n, "text": re.sub(r"\s+", " ", line.strip())[:140]})
    return {"files": files, "counts": counts, "hits": hits, "hosts": sorted(hosts)[:25]}


def targets():
    out = []
    for base in ("packs", "skills"):
        b = os.path.join(ROOT, base)
        for d in sorted(os.listdir(b)):
            if os.path.isdir(os.path.join(b, d)):
                out.append((base + "/" + d, os.path.join(b, d)))
    return out


def render(results):
    L = ["# Pattern scan of the bundled skills", "",
         "Generated by `scripts/audit_packs.py`. **This is not a security review.** It lists places in each folder that deserve a person's attention before the skill is enabled: network calls, running other programs, downloading and running code, reading credentials or the home folder, hidden text. A hit is a place to look, not a finding; a clean row does not mean safe. Prose and data files only count install commands and credential words, because a URL or a command in documentation does nothing by itself. Nothing was executed.", "",
         "| Folder | Files | " + " | ".join(v[0] for v in CATEGORIES.values()) + " |", "|---|---|" + "---|" * len(CATEGORIES)]
    for name, r in results:
        L.append("| `%s` | %d | " % (name, r["files"]) + " | ".join(str(r["counts"][k]) if r["counts"][k] else "-" for k in CATEGORIES) + " |")
    L += ["", "## The hits, by folder", "", "Only folders with at least one hit are listed; the first %d per category are shown." % SHOW, ""]
    for name, r in results:
        if not any(r["counts"].values()):
            continue
        L += ["### `%s`" % name, ""]
        if r["hosts"]:
            L.append("Hosts named in code: " + ", ".join("`%s`" % h for h in r["hosts"][:12]) + ("..." if len(r["hosts"]) > 12 else ""))
            L.append("")
        for k, (label, _) in CATEGORIES.items():
            if r["counts"][k]:
                L.append("- **%s** (%d line%s)" % (label, r["counts"][k], "" if r["counts"][k] == 1 else "s"))
                for h in r["hits"][k]:
                    L.append("  - `%s:%d` `%s`" % (h["file"], h["line"], h["text"].replace("`", "'")))
        L.append("")
    L += ["## How to use this", "",
          "- Before enabling a pack that has hits in *Downloads or installs software*, *Reads credentials* or *Writes outside the project*, open the listed lines.",
          "- A pack with network hosts that you do not recognise should be read before it runs.",
          "- The registry's `vetted` and `risks` fields (in `skills/hyperskill/integrations.json`) record what a person read; this file only says where to start reading.", ""]
    return "\n".join(L)


def main(argv):
    if argv and argv[0] != "--check":
        res = [(a, scan_dir(a)) for a in argv]
        print(render(res))
        return 0
    results = [(n, scan_dir(p)) for n, p in targets()]
    md = render(results)
    data = json.dumps({n: {"files": r["files"], "counts": r["counts"]} for n, r in results}, indent=1) + "\n"
    paths = (os.path.join(ROOT, "docs", "pack-audit.md"), os.path.join(ROOT, "docs", "pack-audit.json"))
    if argv and argv[0] == "--check":
        cur = [open(p, encoding="utf-8").read() if os.path.exists(p) else "" for p in paths]
        return 0 if cur == [md, data] else 1
    for p, t in zip(paths, (md, data)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(t)
    print("wrote docs/pack-audit.md (%d folders)" % len(results))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
