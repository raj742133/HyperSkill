#!/usr/bin/env python3
"""Generate site/data.js from the plugin's real files and a real tracker run.

Everything the launch site shows (phase list, gate items, provider registry,
counts, demo transcript) comes from here, so it cannot drift from the product.
Output is deterministic; tests/test_site.py fails if site/data.js is stale.

  python3 scripts/build_site.py          write site/data.js
  python3 scripts/build_site.py --check  exit 1 if site/data.js is out of date
"""
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRACKER = os.path.join(ROOT, "scripts", "hyperskill.py")
OUT = os.path.join(ROOT, "site", "data.js")

# The demo walks one gate with real commands. Each entry: (shown command, argv).
DEMO = [
    ("hyperskill init --name studentdash", ["init", "--name", "studentdash"]),
    ("hyperskill gate research --pass problem-statement", ["gate", "research", "--pass", "problem-statement"]),
    ("hyperskill advance", ["advance"]),
    ('hyperskill gate research --run alternatives-mapped --cmd "test -s docs/research.md"',
     ["gate", "research", "--run", "alternatives-mapped", "--cmd", "test -s docs/research.md"]),
    ("hyperskill integrations resolve video-continuous", ["integrations", "resolve", "video-continuous"]),
]


def load(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return json.load(f)


def run_demo():
    steps = []
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, HOME=os.path.join(tmp, "home"), PATH="/usr/bin:/bin")
        os.makedirs(env["HOME"])
        proj = os.path.join(tmp, "proj")
        os.makedirs(proj)
        for shown, argv in DEMO:
            extra = []
            if argv[:2] == ["gate", "research"] and "--pass" in argv:
                extra = ["--evidence", "docs/research.md section 1 read and confirmed by owner"]
            r = subprocess.run([sys.executable, TRACKER, "--root", proj] + argv + extra,
                               capture_output=True, text=True, env=env)
            out = (r.stdout + r.stderr).strip()
            out = out.replace(proj, ".")
            steps.append({"cmd": shown, "out": out, "ok": r.returncode == 0})
    return steps


def count_tests():
    n = 0
    tdir = os.path.join(ROOT, "tests")
    for name in sorted(os.listdir(tdir)):
        if name.startswith("test_") and name.endswith(".py"):
            with open(os.path.join(tdir, name), encoding="utf-8") as f:
                n += len(re.findall(r"^\s+def test_", f.read(), re.M))
    return n


def build():
    gates = load("skills/hyperskill/gates.json")["phases"]
    reg = load("skills/hyperskill/integrations.json")
    phases = [{"id": p["id"], "title": p["title"], "skill": p["skill"], "slots": p.get("slots", []),
               "gate": [{"id": g["id"], "text": g["text"]} for g in p["gate"]]} for p in gates]
    providers = []
    for pid, v in reg["providers"].items():
        if v.get("builtin"):
            continue
        slots = [s for s, sd in reg["slots"].items() if pid in sd["providers"]]
        providers.append({"id": pid, "name": v["name"], "repo": v.get("repo", ""), "kind": v.get("kind", ""),
                          "license": v.get("license", ""), "policy": v.get("policy", ""), "slots": slots,
                          "risks": v.get("risks", [])})
    policy_counts = {}
    for p in providers:
        policy_counts[p["policy"]] = policy_counts.get(p["policy"], 0) + 1
    data = {
        "counts": {
            "phases": len(phases),
            "gateItems": sum(len(p["gate"]) for p in phases),
            "slots": len(reg["slots"]),
            "providers": len(providers),
            "tests": count_tests(),
            "packs": len(json.load(open(os.path.join(ROOT, "packs", "manifest.json"), encoding="utf-8"))["packs"]),
            "picks": sum(len(g["items"]) for g in json.load(open(os.path.join(ROOT, "skills", "hyperskill", "catalog.json"), encoding="utf-8"))["groups"]),
        },
        "policyCounts": policy_counts,
        "phases": phases,
        "providers": providers,
        "demo": run_demo(),
    }
    return "// Generated by scripts/build_site.py. Do not edit.\nwindow.HS = " + json.dumps(data, indent=1) + ";\n"


def main():
    text = build()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        if not same:
            print("site/data.js is out of date: run python3 scripts/build_site.py", file=sys.stderr)
            sys.exit(1)
        print("site/data.js is up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
